# Capitalize = only first letter

name1 = input("Enter your name: ")
result1 = name1.capitalize()  # Capitalize the first letter
print(result1)

# Upper Method = all uppercase 

name2 = input("Enter your name: ")
result2 = name2.upper() # All Uppercase
print(result2)

# Lower

name3 = input("Enter your name: ")
result3 = name3.lower() # All Lowercase
print(result3)
