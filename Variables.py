# Variable a container for storing data values. A variable is created the moment you first assign a value to it.
# string str, float, integer int, boolean bool
# f-string is a format string literal that allows you to embed expressions inside string literals, using curly braces {}. The expressions are evaluated at runtime and then formatted using the __format__ protocol.


# Strings
name = "Yanji"
food = "burger"

print(name)
print(f"You like {food}.")

# Integers
age = 19
height = 1.65

print(height)
print(f"You are {age} years old.")

# Boolean
is_student = True
if is_student:
    print("You are a student.")
else:    print("You are not a student.")

# Float
price = 6.70
print(f"The price of the item is ${price}.")







