# IsDigit = checks if its a digit

name1 = input("Enter your name: ")
result1 = name1.isdigit()  # Returns a Boolean if its a digit or not
print(result1)

# IsAlpha = checks if its an alphabet

name2 = input("Enter your name: ")
result2 = name2.isalpha()  # Returns a Boolean if its an alphabet or not
print(result2)