# Count Method = we can count many character within the string
phone_num1 = (input("Enter your phone number: "))

result1 = phone_num1.count("-")
print(result1)

# Replace Method = replace whatever u put inside the method
phone_num2 = (input("Enter your phone number: "))

phone_num2 = phone_num2.replace(" ", "-") # 2nd quotations replaces
print(phone_num2)
